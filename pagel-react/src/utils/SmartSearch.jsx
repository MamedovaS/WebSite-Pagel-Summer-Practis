const UKR_STOP_WORDS = new Set([
  'для', 'на', 'в', 'з', 'під', 'по', 'та', 'і', 'або', 'про',
  'як', 'що', 'при', 'без', 'через', 'від', 'до', 'за', 'над'
]);

// Карта автоматичної зміни розкладки (English -> Ukrainian)
const ENG_TO_UKR = {
  'q':'й','w':'ц','e':'у','r':'к','t':'е','y':'н','u':'г','i':'ш','o':'щ','p':'з','[':'х',']':'ї',
  'a':'ф','s':'і','d':'в','f':'а','g':'п','h':'р','j':'о','k':'л','l':'д',';':'ж','\'':'є',
  'z':'я','x':'ч','c':'с','v':'м','b':'и','n':'т','m':'ь',',':'б','.':'ю'
};

function fixKeyboardLayout(text) {
  // Якщо запит містить суто латиницю, але схожий на укр слова (не схожий на код типу V1/50)
  if (/^[a-z;\s]+$/i.test(text) && !/\d/.test(text)) {
    return text.toLowerCase().split('').map(char => ENG_TO_UKR[char] || char).join('');
  }
  return text;
}

// ============================================
// 2. NLP: ЛЕГКИЙ УКРАЇНСЬКИЙ СТЕМЕР (STEMMER)
// ============================================

function stemUkrainianWord(word) {
  if (!word || word.length <= 3) return word;

  return word
    .replace(/(іша|іше|іший|іших|ішим|ішими|ішою|іші|іших)$/i, '')
    .replace(/(ому|ого|ому|ими|іми|его|ього|ньому)$/i, '')
    .replace(/(ання|ення|іння|яння|ами|ями|ом|ем|єм|ам|ям)$/i, '')
    .replace(/(ий|ій|а|я|е|є|и|і|о|у|ю|ь|ові|еві|ува|юва)$/i, '');
}

