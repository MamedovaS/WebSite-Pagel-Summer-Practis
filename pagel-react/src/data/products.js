// Отримати продукт за ID
export const getProductById = (id) => {
  return productsData[id] || null;
};

// Отримати продукти за категорією
export const getProductsByCategory = (category) => {
  return Object.values(productsData).filter(
    product => product.category === category
  );
};

// Отримати продукти за категорією та підкатегорією
export const getProductsByCategoryAndSubcategory = (category, subcategory) => {
  return Object.values(productsData).filter(
    product => product.category === category && product.subcategory === subcategory
  );
};

// Отримати всі продукти
export const getAllProducts = () => {
  return Object.values(productsData);
};

// Отримати категорії продуктів з кількістю
export const getProductCategories = () => {
  const categories = {};
  Object.values(productsData).forEach(product => {
    if (!categories[product.category]) {
      categories[product.category] = 0;
    }
    categories[product.category]++;
  });
  return categories;
};

// Пошук продуктів за назвою
export const searchProducts = (query) => {
  const lowerQuery = query.toLowerCase();
  return Object.values(productsData).filter(
    product => 
      product.title.toLowerCase().includes(lowerQuery) ||
      product.subtitle.toLowerCase().includes(lowerQuery) ||
      product.applications.some(app => app.toLowerCase().includes(lowerQuery))
  );
};