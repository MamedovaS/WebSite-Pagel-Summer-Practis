// 5. НАЛАШТУВАННЯ FUSE.JS ТА ІНДЕКСУВАННЯ
// ============================================

const fuseOptions = {
  includeScore: true,
  threshold: 0.4,
  ignoreLocation: true,
  minMatchCharLength: 2,
  useExtendedSearch: true,
  keys: [
    { name: 'title', weight: 0.4 },
    { name: 'subtitle', weight: 0.2 },
    { name: 'searchStems', weight: 0.2 },
    { name: 'applications', weight: 0.1 },
    { name: 'properties', weight: 0.05 },
    { name: 'features', weight: 0.05 },
  ],
};

let fuseInstance = null;
let indexedAt = 0;

function prepareProductsForIndex(products) {
  return products.map(p => {
    const fullText = `${p.title} ${p.subtitle || ''} ${p.applications || ''} ${p.properties || ''}`;
    const tokens = fullText.toLowerCase().split(/[^\wа-яєіїґ\d/]+/i).filter(Boolean);
    const stems = Array.from(new Set(tokens.map(stemUkrainianWord)));

    return {
      ...p,
      searchStems: stems.join(' ')
    };
  });
}

function getFuse(forceRebuild = false) {
  const products = getAllProducts();
  if (!fuseInstance || forceRebuild || products.length !== indexedAt) {
    const prepared = prepareProductsForIndex(products);
    fuseInstance = new Fuse(prepared, fuseOptions);
    indexedAt = products.length;
  }
  return fuseInstance;
}

