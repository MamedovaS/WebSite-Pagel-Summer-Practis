// 4. ТОКЕНІЗАЦІЯ ТА НОРМАЛІЗАЦІЯ
// ============================================

function normalize(str) {
  return str
    .toLowerCase()
    .trim()
    .replace(/['"«»`’]/g, '')
    .replace(/\s+/g, ' ');
}

function preprocessQuery(query) {
  let text = normalize(query);
  text = fixKeyboardLayout(text);

  const rawTokens = text.split(/[^\wа-яєіїґ\d/]+/i).filter(Boolean);

  const cleanTokens = [];
  const stems = [];

  rawTokens.forEach(token => {
    if (UKR_STOP_WORDS.has(token)) return;

    cleanTokens.push(token);

    if (!/\d/.test(token)) {
      const stem = stemUkrainianWord(token);
      if (stem && stem !== token) {
        stems.push(stem);
      }
    }
  });

  return {
    raw: text,
    tokens: cleanTokens,
    stems: stems
  };
}

// Розширення запиту синонімами (за групами слів) + фразами
function expandWithSynonyms(searchTerms, rawQuery) {
  const extra = [];

  // 1. Групи слів — збіг по токену або стему
  searchTerms.forEach(term => {
    SYNONYM_GROUPS.forEach(group => {
      const isMatched = group.some(syn => {
        const synNorm = syn.toLowerCase();
        return synNorm === term
          || stemUkrainianWord(synNorm) === term
          || stemUkrainianWord(synNorm) === stemUkrainianWord(term);
      });
      if (isMatched) {
        extra.push(...group);
      }
    });
  });

  // 2. Побутові словосполучення — збіг підрядком у сирому запиті
  PHRASE_TO_TERMS.forEach(({ phrase, terms }) => {
    if (rawQuery.includes(phrase)) {
      extra.push(...terms);
    }
  });

  return extra;
}

